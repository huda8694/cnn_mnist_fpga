`timescale 1ns / 1ps
// -----------------------------------------------------------------------------
// cnn_dense.v - both Dense layers of the notebook on ONE multiply-accumulate unit,
//               exploiting the 80 % weight pruning (sparse "CSR" weight stream)
//
//   layer 1 : 5408 -> 128, ReLU      (rows   0..127)
//   layer 2 :  128 ->  10, logits    (rows 128..137)
//
// Weight storage: only the NON-ZERO int8 weights are stored, row by row, as entries
//   { delta[3:0], weight[7:0] }.   Entry address runs linearly through the whole ROM
//   (layer 1 rows first, then layer 2), so no address arithmetic is needed between rows.
//   idx = base + delta, then base = idx + 1   (base = 0 at the start of a layer-1 row,
//   5408 at the start of a layer-2 row, where the hidden activations live in the same RAM).
//   A gap > 15 is bridged with padding entries (delta = 15, weight = 0).
//   row_len[r] (entries per row) and the biases come from the generated parameter ROM.
//
// Integer arithmetic (mirrored exactly by python/quantize_export.py):
//   acc  = sum_e W[e] * a[idx(e)] + B[r]               a : u8 feature,  W : int8
//   layer 1 :  a2[r] = min(255, (min(max(acc,0), 2^24-1) * M2 + 2^(S2-1)) >> S2)
//   layer 2 :  score[k] = acc;   pred = argmax (lowest index wins a tie)
//
// Entry pipeline (A = clock in which the entry address is presented to the ROM):
//   A  : ent_addr -> ROM (synchronous read)
//   S1 : ROM data (w, d)
//   S2 : second register stage (w2, d2); idx = base + d2
//   S3 : idx_r drives the feature RAM read address
//   S4 : feature byte valid (RAM output)
//   S5 : operand registers a5 / w5  (both multiplier inputs come straight from flip-flops)
//   S6 : product valid -> accumulate
//   S7 : accumulator holds the entry   (v7 & l7 = last entry of the row -> acc is final)
//
// After reset the engine first scans the whole weight ROM and compares a checksum with the
// value generated by the Python script (rom_ok): this reveals a missing / wrong .mem file.
// -----------------------------------------------------------------------------
module cnn_dense #(
    parameter W_FILE = "mnist_w.mem",             // sparse weight bytes
    parameter D_FILE = "mnist_d.mem"              // index-delta nibbles
)(
    input  wire         clk,
    input  wire         rst,
    input  wire         start,                   // 1-clock pulse (features must be in the RAM)
    output reg          busy = 1'b1,
    output reg          done = 1'b0,
    // feature RAM: synchronous read port + write port for the hidden activations
    output wire [12:0]  fm_raddr,
    input  wire [7:0]   fm_rdata,
    output reg          fm_we    = 1'b0,
    output reg  [12:0]  fm_waddr = 13'd0,
    output reg  [7:0]   fm_wdata = 8'd0,
    // results
    output reg  [3:0]   pred = 4'd0,
    output wire [319:0] scores_flat,
    // ROM self-test
    output reg          scan_done = 1'b0,
    output reg          rom_ok    = 1'b0
);
    localparam [7:0]  LAST_ROW = 8'd137;
    localparam [12:0] L2_BASE  = 13'd5408;

    localparam [3:0] D_INIT = 4'd0, D_SCAN = 4'd1, D_IDLE = 4'd2, D_LOAD = 4'd3, D_ISSUE = 4'd4,
                     D_WAIT = 4'd5, D_FIN1 = 4'd6, D_FIN2 = 4'd7, D_FIN3 = 4'd8, D_FIN4 = 4'd9,
                     D_NEXT = 4'd10, D_DONE = 4'd11;

    reg [3:0]  state     = D_INIT;
    reg [7:0]  row       = 8'd0;
    reg [17:0] ent_addr  = 18'd0;
    reg [17:0] rem       = 18'd0;
    reg [12:0] base      = 13'd0;
    reg        scan_mode = 1'b1;
    reg [31:0] chk       = 32'd0;

    // ------------------------------------------------------------ generated parameter ROMs
    wire [12:0]        rlen;
    wire signed [27:0] rbias;
    wire [15:0]        m2;
    wire [5:0]         s2;
    wire [17:0]        n_ent;
    wire [31:0]        chk_exp;
    mnist_dense_params u_dp (.row(row), .row_len(rlen), .row_bias(rbias),
                             .m2(m2), .s2(s2), .n_ent(n_ent), .w_chk(chk_exp));

    wire [7:0] rom_w;
    wire [3:0] rom_d;
    mnist_sparse_rom #(.W_FILE(W_FILE), .D_FILE(D_FILE)) u_rom (.clk(clk), .addr(ent_addr), .w(rom_w), .d(rom_d));

    // ------------------------------------------------------------ entry pipeline
    wire iss      = (state == D_ISSUE) || (state == D_SCAN);
    wire last_iss = (rem == 18'd1);

    reg        v1 = 1'b0, v2 = 1'b0, v3 = 1'b0, v4 = 1'b0, v5 = 1'b0, v6 = 1'b0, v7 = 1'b0;
    reg        l1 = 1'b0, l2 = 1'b0, l3 = 1'b0, l4 = 1'b0, l5 = 1'b0, l6 = 1'b0, l7 = 1'b0;
    reg [7:0]  w2 = 8'd0, w3 = 8'd0, w4 = 8'd0, w5 = 8'd0, a5 = 8'd0;
    reg [3:0]  d2 = 4'd0;
    reg [12:0] idx_r = 13'd0;
    reg signed [16:0] prod = 17'sd0;
    reg signed [27:0] acc  = 28'sd0;

    wire [12:0] idx_c = base + {9'd0, d2};
    assign fm_raddr = idx_r;
    wire signed [27:0] prod_x = {{11{prod[16]}}, prod};

    always @(posedge clk) begin
        // S1: tags of the ROM data
        v1 <= iss;       l1 <= iss && last_iss;
        // S2: second register stage
        w2 <= rom_w;     d2 <= rom_d;      v2 <= v1;  l2 <= l1;
        // S3: feature index
        idx_r <= idx_c;  w3 <= w2;         v3 <= v2;  l3 <= l2;
        if (state == D_LOAD)  base <= row[7] ? L2_BASE : 13'd0;
        else if (v2)          base <= idx_c + 13'd1;
        // S4: feature RAM data is valid in this clock (fm_rdata)
        w4 <= w3;        v4 <= v3;  l4 <= l3;
        // S5: operand registers
        a5 <= fm_rdata;  w5 <= w4;         v5 <= v4;  l5 <= l4;
        // S6: product (register -> DSP -> register)
        prod <= $signed({1'b0, a5}) * $signed(w5);
        v6 <= v5;        l6 <= l5;
        // S7: accumulate
        if (state == D_LOAD)  acc <= 28'sd0;
        else if (v6)          acc <= acc + prod_x;
        v7 <= v6;        l7 <= l6;
        
        // ROM checksum (scan mode): rotate-left-1 and xor with {delta, weight}
        if (state == D_INIT) begin
            chk <= 32'd0;
        end else if (scan_mode && v2) begin
            chk <= {chk[30:0], chk[31]} ^ {20'd0, d2, w2};
        end
    end

    // ------------------------------------------------------------ results
    reg signed [27:0] sum    = 28'sd0;
    reg signed [27:0] best   = 28'sd0;
    reg [23:0]        relu_c = 24'd0;
    reg [39:0]        rqp    = 40'd0;
    reg signed [27:0] scores_r [0:9];

    genvar g;
    generate
        for (g = 0; g < 10; g = g + 1) begin : g_scores
            assign scores_flat[32*g +: 32] = {{4{scores_r[g][27]}}, scores_r[g]};
        end
    endgenerate

    wire [39:0] rnd2 = 40'd1 << (s2 - 6'd1);
    wire [39:0] q    = (rqp + rnd2) >> s2;

    // ------------------------------------------------------------ control FSM
    always @(posedge clk) begin
        done  <= 1'b0;
        fm_we <= 1'b0;
        if (rst) begin
            state     <= D_INIT;
            busy      <= 1'b1;
            scan_mode <= 1'b1;
            scan_done <= 1'b0;
            rom_ok    <= 1'b0;
        end else begin
            case (state)
                D_INIT: begin                                   // start the ROM self-test scan
                    ent_addr <= 18'd0;
                    rem      <= n_ent;
                   // chk      <= 32'd0;
                    state    <= D_SCAN;
                end

                D_SCAN: begin
                    ent_addr <= ent_addr + 18'd1;
                    rem      <= rem - 18'd1;
                    if (last_iss) state <= D_WAIT;
                end

                D_IDLE: if (start) begin
                    busy     <= 1'b1;
                    row      <= 8'd0;
                    ent_addr <= 18'd0;
                    state    <= D_LOAD;
                end

                D_LOAD: begin                                   // acc and base are initialised in the datapath
                    rem   <= {5'd0, rlen};
                    state <= (rlen == 13'd0) ? D_FIN1 : D_ISSUE;
                end

                D_ISSUE: begin
                    ent_addr <= ent_addr + 18'd1;
                    rem      <= rem - 18'd1;
                    if (last_iss) state <= D_WAIT;
                end

                D_WAIT: if (v7 && l7) begin
                    if (scan_mode) begin
                        scan_mode <= 1'b0;
                        scan_done <= 1'b1;
                        rom_ok    <= (chk == chk_exp);
                        busy      <= 1'b0;
                        state     <= D_IDLE;
                    end else begin
                        state <= D_FIN1;
                    end
                end

                D_FIN1: begin
                    sum   <= acc + rbias;
                    state <= D_FIN2;
                end

                D_FIN2: begin
                    if (row[7]) begin                           // layer 2: logits + argmax
                        scores_r[row[3:0]] <= sum;
                        if (row[3:0] == 4'd0 || sum > best) begin
                            best <= sum;
                            pred <= row[3:0];
                        end
                        state <= D_NEXT;
                    end else begin                              // layer 1: ReLU, clamp to 24 bits
                        relu_c <= sum[27] ? 24'd0 : (|sum[26:24]) ? 24'hFFFFFF : sum[23:0];
                        state  <= D_FIN3;
                    end
                end

                D_FIN3: begin
                    rqp   <= relu_c * m2;
                    state <= D_FIN4;
                end

                D_FIN4: begin                                   // requantise, write hidden activation
                    fm_we    <= 1'b1;
                    fm_waddr <= L2_BASE + {5'd0, row};
                    fm_wdata <= (|q[39:8]) ? 8'hFF : q[7:0];
                    state    <= D_NEXT;
                end

                D_NEXT: begin
                    if (row == LAST_ROW) begin
                        state <= D_DONE;
                    end else begin
                        row   <= row + 8'd1;
                        state <= D_LOAD;
                    end
                end

                D_DONE: begin
                    busy  <= 1'b0;
                    done  <= 1'b1;
                    state <= D_IDLE;
                end

                default: state <= D_INIT;
            endcase
        end
    end
endmodule
